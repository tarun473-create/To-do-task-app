// Shares the single client codebase (../index.html, ../css, ../js) with the Cloudflare Worker:
//  • copies css/js into public/app/ (served by Workers Static Assets)
//  • writes src/gen/client.js with:
//      createT360(config) — the rules engine (../js/store.js + ../js/engine.js) as ordinary module
//        code wrapped in a factory, so every request gets its own isolated engine instance
//        (no eval / vm, which Workers do not allow)
//      SHELL_HTML — the app shell; SCHEMA — the D1 schema statements for /setup
import { readFileSync, writeFileSync, mkdirSync, cpSync, rmSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const cf = join(here, '..'), root = join(cf, '..');
for (const f of ['index.html', 'css/styles.css', 'js/store.js', 'js/engine.js', 'js/remote.js']) {
  if (!existsSync(join(root, f))) { console.error(`sync: ${f} not found — build from the full repository.`); process.exit(1); }
}
rmSync(join(cf, 'public/app'), { recursive: true, force: true });
mkdirSync(join(cf, 'public/app'), { recursive: true });
cpSync(join(root, 'css'), join(cf, 'public/app/css'), { recursive: true });
cpSync(join(root, 'js'), join(cf, 'public/app/js'), { recursive: true });

let html = readFileSync(join(root, 'index.html'), 'utf8')
  .replace('href="css/styles.css"', 'href="/app/css/styles.css"')
  .replace(/src="js\//g, 'src="/app/js/')
  .replace('<script src="/app/js/store.js"></script>', '<!--T360_BOOT-->\n<script src="/app/js/store.js"></script>')
  .replace('<script src="/app/js/app.js"></script>', '<script src="/app/js/remote.js"></script>\n<script src="/app/js/app.js"></script>');
if (!html.includes('<!--T360_BOOT-->')) { console.error('sync: could not prepare the HTML shell'); process.exit(1); }

const store = readFileSync(join(root, 'js/store.js'), 'utf8');
const engine = readFileSync(join(root, 'js/engine.js'), 'utf8');
const schema = readFileSync(join(cf, 'migrations/0001_init.sql'), 'utf8').split(/^-- ;;$/m).map(s => s.trim()).filter(s => s && !/^(--[^\n]*\n?)+$/.test(s));
mkdirSync(join(cf, 'src/gen'), { recursive: true });
writeFileSync(join(cf, 'src/gen/client.js'),
`// AUTO-GENERATED by scripts/sync.mjs from ../js/store.js and ../js/engine.js — do not edit.
/* eslint-disable */
export function createT360(config) {
  const window = { T360_CONFIG: config || { mode: 'server' } };
  const localStorage = undefined;
${store}
;
${engine}
;
  window.T360.store.save = function () {};
  return window.T360;
}
export const SHELL_HTML = ${JSON.stringify(html)};
export const SCHEMA = ${JSON.stringify(schema)};
`);
console.log(`sync: client assets copied; engine factory and ${schema.length} schema statements generated`);
