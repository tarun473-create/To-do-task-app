// Shares the single client codebase (../index.html, ../css, ../js) with the server edition:
//  • copies css/js into public/app/ so the browser loads them from this server
//  • generates lib/generated/client.ts with the rules-engine source (run server-side in a
//    sandbox, so client and server enforce exactly the same rules) and the HTML shell.
import { readFileSync, writeFileSync, mkdirSync, cpSync, existsSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const server = join(here, '..');
const root = join(server, '..');
for (const f of ['index.html', 'css/styles.css', 'js/store.js', 'js/engine.js', 'js/remote.js', 'js/app.js', 'db/schema.sql']) {
  if (!existsSync(join(root, f))) {
    console.error(`sync-client: ${f} not found in ${root}. The server must be built from the full repository ` +
      `(on Vercel keep "Include files outside the root directory" enabled).`);
    process.exit(1);
  }
}

rmSync(join(server, 'public/app'), { recursive: true, force: true });
mkdirSync(join(server, 'public/app'), { recursive: true });
cpSync(join(root, 'css'), join(server, 'public/app/css'), { recursive: true });
cpSync(join(root, 'js'), join(server, 'public/app/js'), { recursive: true });

let html = readFileSync(join(root, 'index.html'), 'utf8')
  .replace('href="css/styles.css"', 'href="/app/css/styles.css"')
  .replace(/src="js\//g, 'src="/app/js/')
  .replace('<script src="/app/js/store.js"></script>', '<!--T360_BOOT-->\n<script src="/app/js/store.js"></script>')
  .replace('<script src="/app/js/app.js"></script>', '<script src="/app/js/remote.js"></script>\n<script src="/app/js/app.js"></script>');
if (!html.includes('<!--T360_BOOT-->') || !html.includes('/app/js/remote.js')) { console.error('sync-client: could not prepare HTML shell'); process.exit(1); }

const store = readFileSync(join(root, 'js/store.js'), 'utf8');
const engine = readFileSync(join(root, 'js/engine.js'), 'utf8');
mkdirSync(join(server, 'lib/generated'), { recursive: true });
writeFileSync(join(server, 'lib/generated/client.ts'),
  `// AUTO-GENERATED by scripts/sync-client.mjs — do not edit.\n` +
  `export const STORE_SRC: string = ${JSON.stringify(store)};\n` +
  `export const ENGINE_SRC: string = ${JSON.stringify(engine)};\n` +
  `export const SHELL_HTML: string = ${JSON.stringify(html)};\n` +
  `export const SCHEMA_SQL: string = ${JSON.stringify(readFileSync(join(root, 'db/schema.sql'), 'utf8'))};\n`);
console.log('sync-client: client assets and engine source synced');
